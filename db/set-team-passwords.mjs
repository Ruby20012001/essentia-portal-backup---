/**
 * Set the WIO team's portal passwords.
 *
 *   node db/set-team-passwords.mjs
 *
 * Asks for a password for each of the six accounts, hashes it with the same
 * scrypt scheme the app verifies against (lib/auth/password.ts), and writes
 * db/037_wio_team_passwords.sql containing ONLY the hashes.
 *
 * The passwords you type are never printed, never stored, and never written to
 * the repository — only their hashes are, and a scrypt hash cannot be turned
 * back into the password. Whoever runs this is the only person who knows them.
 *
 * Re-run it any time to change a password; it rewrites the file, and the
 * migration updates the rows in place.
 */
import { randomBytes, scrypt } from "node:crypto";
import { promisify } from "node:util";
import { writeFileSync } from "node:fs";
import { createInterface } from "node:readline";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scryptAsync = promisify(scrypt);
const HERE = dirname(fileURLToPath(import.meta.url));

const PEOPLE = [
  ["dipmallya.wio@essentia.in", "Dipmalya Das", "Team Lead"],
  ["neeraj.wio@essentia.in", "Neeraj Jangra", "Team Lead"],
  ["wio.vishal@essentia.in", "Vishal Kaushik", "Team Lead"],
  ["wio.anshul@essentia.in", "Anshul Soni", "Senior Draughtsman"],
  ["wio.atul@essentia.in", "Atul Yadav", "Senior Draughtsman"],
  ["Jyoti.drafting@essentia.in", "Jyoti Yadav", "Senior Draughtsman"],
];

const rl = createInterface({ input: process.stdin, output: process.stdout });
const ask = (q) => new Promise((res) => rl.question(q, res));

console.log("");
console.log("  WIO team ke portal passwords");
console.log("  ----------------------------");
console.log("  Har account ke liye password likho (kam se kam 8 characters).");
console.log("  Ye screen par dikhega, isliye akele baith kar karna.");
console.log("  Khaali chhodoge to wo account skip ho jayega.");
console.log("");

const rows = [];
for (const [email, name, role] of PEOPLE) {
  let pw = "";
  while (true) {
    pw = (await ask(`  ${name} (${role})\n    password: `)).trim();
    if (pw === "") break;
    if (pw.length < 8) {
      console.log("    -> kam se kam 8 characters chahiye. Dobara.\n");
      continue;
    }
    break;
  }
  if (pw === "") {
    console.log("    -> skipped\n");
    continue;
  }
  const salt = randomBytes(16);
  const key = await scryptAsync(pw, salt, 64);
  rows.push({ email, name, hash: `${salt.toString("hex")}:${key.toString("hex")}` });
  console.log("    -> set\n");
}
rl.close();

if (rows.length === 0) {
  console.log("  Kuch set nahi hua. Koi file nahi likhi.\n");
  process.exit(0);
}

const sql = `-- =====================================================================
-- 037 — WIO TEAM · PORTAL PASSWORDS
--
--   Generated by db/set-team-passwords.mjs. Do not hand-edit; re-run the
--   script to change a password.
--
--   These are scrypt hashes in the format lib/auth/password.ts verifies —
--   "<saltHex>:<keyHex>". A hash cannot be reversed into the password, so this
--   file is safe to commit. The passwords themselves were typed by whoever ran
--   the script and are not recorded anywhere.
--
--   auth_provider moves to 'local' for these accounts so the password provider
--   will accept them. db/035 created them as 'entra' with no password, on the
--   assumption Microsoft sign-in would land first; it has not, and the team
--   needs to get in.
--
--   WHEN MICROSOFT SIGN-IN IS CONFIGURED: set auth_provider back to 'entra' and
--   clear password_hash, so there is one way in rather than two. Leaving both
--   live means a password can be used to bypass whatever the tenant enforces.
--
--   Idempotent — re-running sets the same hashes again.
-- =====================================================================

UPDATE public.users SET password_hash = v.hash, auth_provider = 'local'
FROM (VALUES
${rows.map((r) => `  -- ${r.name}\n  ('${r.email}', '${r.hash}')`).join(",\n")}
) AS v(email, hash)
WHERE lower(public.users.email) = lower(v.email);

DO $$
DECLARE n INTEGER;
BEGIN
  SELECT COUNT(*) INTO n FROM public.users
   WHERE password_hash IS NOT NULL AND auth_provider = 'local'
     AND lower(email) IN (${rows.map((r) => `'${r.email.toLowerCase()}'`).join(", ")});
  IF n <> ${rows.length} THEN
    RAISE EXCEPTION 'Expected ${rows.length} team accounts with a password, found %. '
      'An email may not match db/035.', n;
  END IF;
END $$;
`;

const out = join(HERE, "037_wio_team_passwords.sql");
writeFileSync(out, sql);

console.log(`  Ho gaya — ${rows.length} account(s).`);
console.log(`  File bani: db/037_wio_team_passwords.sql (sirf hashes)`);
console.log("");
console.log("  Ab bas database restart karo — file apne aap load ho jayegi.");
console.log("");
console.log("  Passwords sirf aapko pata hain. Kahin save nahi hue.");
console.log("");
