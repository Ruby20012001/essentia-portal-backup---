/**
 * Set the design team's portal passwords, and let them into the decks.
 *
 *   node db/set-design-passwords.mjs
 *
 * Asks for a password for each of the five design accounts, hashes it with the
 * same scrypt scheme the app verifies against (lib/auth/password.ts), and
 * writes db/043_design_team_accounts.sql containing ONLY the hashes.
 *
 * The passwords you type are never printed back, never stored, and never
 * written to the repository — only their hashes are, and a scrypt hash cannot
 * be turned back into the password. Whoever runs this is the only person who
 * knows them.
 *
 * Unlike the WIO team's script, this one CREATES the account if it is not
 * there: these five have never signed in to the portal, so there is nothing to
 * update. It also adds each of them to ee.concept_deck_editors, which is the
 * list /decks opens for.
 *
 * Re-run it any time to change a password; it rewrites the file, and the
 * migration updates the rows in place.
 */
import { randomBytes, scrypt } from "node:crypto";
import { promisify } from "node:util";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createInterface } from "node:readline";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scryptAsync = promisify(scrypt);
const HERE = dirname(fileURLToPath(import.meta.url));

/* The five Monica named on 10 Sep 2026. A name here is what the portal shows
   against an edit, so it is the name the person is called, not their address. */
const PEOPLE = [
  ["design.vishakha@essentia.in", "Vishakha", "Design"],
  ["design.akanshamalik@essentia.in", "Akansha Malik", "Design"],
  ["design.ritu@essentia.in", "Ritu", "Design"],
  ["design.lavika@essentia.in", "Lavika", "Design"],
  ["design.jiya@essentia.in", "Jiya", "Design"],
];

const rl = createInterface({ input: process.stdin, output: process.stdout });

/* Once stdin has ended — piped input, or a Ctrl-D — every further question
   would throw. Treat it as an empty answer instead, so the run ends with the
   people it did get rather than a stack trace over the ones it did not. */
let closed = false;
rl.on("close", () => { closed = true; });
const ask = (q) =>
  closed ? Promise.resolve("") : new Promise((res) => rl.question(q, res));

console.log("");
console.log("  Design team ke portal passwords");
console.log("  -------------------------------");
console.log("  Har account ke liye password likho (kam se kam 8 characters).");
console.log("  Ye screen par dikhega, isliye akele baith kar karna.");
console.log("  Khaali chhodoge to wo account skip ho jayega.");
console.log("");

const OUT = join(HERE, "043_design_team_accounts.sql");
const existing = new Map();
if (existsSync(OUT)) {
  const prev = readFileSync(OUT, "utf8");
  for (const m of prev.matchAll(/\('([^']+)',\s*'([^']+)',\s*'([0-9a-f]+:[0-9a-f]+)'\)/g)) {
    existing.set(m[1].toLowerCase(), m[3]);
  }
}

const rows = [];
for (const [email, name, role] of PEOPLE) {
  let pw = "";
  while (true) {
    pw = (await ask(`  ${name} (${role})\n    password: `)).trim();
    if (pw === "") break;
    if (pw.length < 8) {
      console.log("    -> kam se kam 8 characters chahiye. Dobara.\n");
      continue;
    }
    break;
  }
  if (pw === "") {
    const kept = existing.get(email.toLowerCase());
    if (kept) {
      rows.push({ email, name, hash: kept });
      console.log("    -> pehle jaisa hi rakha\n");
    } else {
      console.log("    -> skipped\n");
    }
    continue;
  }
  const salt = randomBytes(16);
  const key = await scryptAsync(pw, salt, 64);
  rows.push({ email, name, hash: `${salt.toString("hex")}:${key.toString("hex")}` });
  console.log("    -> set\n");
}
rl.close();

if (rows.length === 0) {
  console.log("  Kuch set nahi hua. Koi file nahi likhi.\n");
  process.exit(0);
}

const values = rows
  .map((r) => `  ('${r.email}', '${r.name.replace(/'/g, "''")}', '${r.hash}')`)
  .join(",\n");
const emails = rows.map((r) => `'${r.email.toLowerCase()}'`).join(", ");

const sql = `-- =====================================================================
-- 043 — DESIGN TEAM · ACCOUNTS, PASSWORDS AND THE DECK LIST
--
--   Generated by db/set-design-passwords.mjs. Do not hand-edit; re-run the
--   script to change a password.
--
--   These are scrypt hashes in the format lib/auth/password.ts verifies —
--   "<saltHex>:<keyHex>". A hash cannot be reversed into the password, so this
--   file is safe to commit. The passwords themselves were typed by whoever ran
--   the script and are recorded nowhere.
--
--   Three things happen here, and nothing else:
--     · the account exists (created if it does not, L3, Interior department);
--     · it signs in with a password, at /deck-login;
--     · it is on ee.concept_deck_editors, which is the list /decks opens for.
--
--   These accounts are NOT given anything on the tracker. Someone who is on
--   both sides is on both lists — that is a row in the tracker's own tables,
--   not something this file decides.
--
--   Idempotent — re-running sets the same hashes and adds nobody twice.
-- =====================================================================

INSERT INTO public.users
  (email, full_name, display_name, access_level, department_id, job_title,
   auth_provider, password_hash)
SELECT v.email, v.name, v.name, 'L3', d.id, 'essentia — design',
       'local', v.hash
  FROM (VALUES
${values}
  ) AS v(email, name, hash)
  LEFT JOIN public.departments d ON d.code = 'INTERIOR'
ON CONFLICT (email) DO UPDATE
  SET password_hash = EXCLUDED.password_hash,
      auth_provider = 'local',
      is_active = TRUE;

INSERT INTO ee.concept_deck_editors (user_id)
SELECT id FROM public.users WHERE lower(email) IN (${emails})
ON CONFLICT (user_id) DO NOTHING;

DO $$
DECLARE n INTEGER;
BEGIN
  SELECT COUNT(*) INTO n
    FROM public.users u
    JOIN ee.concept_deck_editors e ON e.user_id = u.id
   WHERE u.password_hash IS NOT NULL AND u.auth_provider = 'local'
     AND lower(u.email) IN (${emails});
  IF n <> ${rows.length} THEN
    RAISE EXCEPTION 'Expected ${rows.length} design accounts with a password on the deck list, found %.', n;
  END IF;
END $$;
`;

writeFileSync(OUT, sql);
console.log(`  Likh diya: db/043_design_team_accounts.sql (${rows.length} account)`);
console.log("  Ab ye file Neon ke SQL editor mein chala do — ya deploy ke saath jayegi.\n");
