/**
 * Put the WIO team's passwords on a database — and nothing else.
 *
 *   PowerShell:  $env:DATABASE_URL="postgres://..."
 *   cmd:         set DATABASE_URL=postgres://...
 *   node db/apply-wio-passwords.mjs
 *
 * WHY THIS EXISTS INSTEAD OF db/migrate.mjs.
 *
 * migrate.mjs runs every file in DEFAULT_FILES, and one of them —
 * 901_design_tracker_fixtures.sql — deletes its six projects by name and
 * inserts them again, erasing the design team's ticks. It is the right tool
 * for standing a database up from nothing and the wrong one for adding one
 * file to a database people are working in.
 *
 * So this applies exactly one file: 060_wio_team_passwords.sql, generated by
 * db/set-wio-passwords.mjs. It runs in a single transaction, so a failed
 * guard leaves nothing half-applied, and it is idempotent — running it twice
 * sets the same hashes.
 *
 * THERE ARE TWO NEON PROJECTS WITH THE SAME NAME, and only one of them is the
 * board the team opens. Before writing anything this prints the host and what
 * the tracker looks like on it — the stamped date and the row counts — and
 * asks you to confirm. Check those against the board in your browser. The
 * handover of 18 Sep 2026 records the real one as AWS Asia Pacific 1
 * (Singapore), host containing `raspy-grass`; the US East 2 (Ohio) project
 * was created by accident. Trust what you see here over either sentence.
 *
 * Nothing here prints a password or a connection string. The hashes are in
 * the SQL file and cannot be reversed; the passwords are only with whoever
 * ran set-wio-passwords.mjs.
 */
import { readFileSync, existsSync } from "node:fs";
import { createInterface } from "node:readline";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import pg from "pg";

const HERE = dirname(fileURLToPath(import.meta.url));
const FILE = "060_wio_team_passwords.sql";
const path = join(HERE, FILE);

if (!process.env.DATABASE_URL) {
  console.error("");
  console.error("  DATABASE_URL set nahi hai.");
  console.error('  PowerShell:  $env:DATABASE_URL="postgres://..."');
  console.error("  cmd:         set DATABASE_URL=postgres://...");
  console.error("");
  process.exit(1);
}

if (!existsSync(path)) {
  console.error("");
  console.error(`  db/${FILE} abhi bani nahi hai.`);
  console.error("  Pehle chalao:  node db/set-wio-passwords.mjs");
  console.error("");
  process.exit(1);
}

const client = new pg.Client({ connectionString: process.env.DATABASE_URL });
await client.connect();

/* The host without the credentials in front of it — enough to tell the two
   Neon projects apart, and nothing anybody should mind seeing. */
const host = process.env.DATABASE_URL.replace(/^[^@]*@/, "").split(/[/?]/)[0];

const [{ stamp }] = (
  await client.query("SELECT today_stamp::text AS stamp FROM ee.tracker_settings LIMIT 1")
).rows;
const [{ wios }] = (
  await client.query("SELECT count(*)::int AS wios FROM ee.tracker_wios")
).rows;
const [{ delays }] = (
  await client.query("SELECT count(*)::int AS delays FROM ee.tracker_delays")
).rows;

console.log("");
console.log("  Ye database:");
console.log(`    host         ${host}`);
console.log(`    read against ${stamp}`);
console.log(`    WIOs         ${wios}`);
console.log(`    delays       ${delays}`);
console.log("");
console.log("  Apne browser me board kholkar milao — wahi stamp aur wahi");
console.log("  ginti dikhni chahiye. Na mile to ye galat database hai.");
console.log("");

const rl = createInterface({ input: process.stdin, output: process.stdout });
const answer = await new Promise((res) => rl.question("  Aage badhein? (haan/na): ", res));
rl.close();

if (!/^(haan|han|y|yes)$/i.test(answer.trim())) {
  console.log("\n  Kuch nahi badla.\n");
  await client.end();
  process.exit(0);
}

process.stdout.write(`\n  ${FILE.padEnd(34)}`);
try {
  await client.query("BEGIN");
  await client.query(readFileSync(path, "utf8"));
  await client.query("COMMIT");
  console.log("ok");
} catch (err) {
  await client.query("ROLLBACK").catch(() => {});
  console.log("FAILED");
  console.log(`\n  ${err.message}\n`);
  await client.end();
  process.exit(1);
}

const { rows } = await client.query(
  `SELECT u.display_name, u.auth_provider,
          (u.password_hash IS NOT NULL) AS can_sign_in, d.code AS dept
     FROM public.users u
     LEFT JOIN public.departments d ON d.id = u.department_id
    WHERE d.code = 'DRAFTING'
    ORDER BY u.access_level, u.display_name`,
);

console.log("");
for (const r of rows) {
  console.log(
    `    ${String(r.display_name).padEnd(10)} ${String(r.auth_provider).padEnd(6)} ` +
      `${r.can_sign_in ? "sign in: ho sakta hai" : "sign in: NAHI"}  ${r.dept}`,
  );
}
console.log("");
console.log("  Ab /login par sign in karke dekho — WIOs tab par Edit dikhna chahiye.");
console.log("");

await client.end();
