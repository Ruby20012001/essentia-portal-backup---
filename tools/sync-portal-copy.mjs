/**
 * The tool, as the portal serves it.
 *
 *   node tools/sync-portal-copy.mjs
 *
 * One file, two homes. `tools/concept-deck-configurator.html` is the thing
 * itself — opened from a laptop it needs no server, no login and no network,
 * which is the whole point of it. `frontend/public/tools/concept-deck.html` is
 * the same bytes, served by the portal, where the deck lives in the database
 * and the name against a change is the account that made it.
 *
 * It is a copy rather than a build step because Vercel builds with the root
 * directory set to `frontend`, and a file that has to exist at build time is
 * better committed than generated by a script nobody remembers to run. This
 * script is how it is kept honest: run it after changing the tool, and the
 * check below fails loudly if the two ever drift.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/* fileURLToPath, not the URL's pathname: a repo checked out under a folder with
   a space in its name arrives here as %20 otherwise, and the read fails */
const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.join(here, 'concept-deck-configurator.html');
const target = path.join(here, '..', 'frontend', 'public', 'tools', 'concept-deck.html');

const check = process.argv.includes('--check');
const src = fs.readFileSync(source);
const same = fs.existsSync(target) && Buffer.compare(src, fs.readFileSync(target)) === 0;

if (check) {
  if (same) {
    console.log('in step · frontend/public/tools/concept-deck.html matches the tool');
    process.exit(0);
  }
  console.error('OUT OF STEP — the portal copy is not the tool.');
  console.error('Run: node tools/sync-portal-copy.mjs');
  process.exit(1);
}

if (same) {
  console.log('already in step, nothing copied');
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, src);
  console.log('copied', (src.length / 1024).toFixed(0) + ' KB → frontend/public/tools/concept-deck.html');
}
