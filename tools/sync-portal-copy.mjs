/**
 * The tools, as the portal serves them.
 *
 *   node tools/sync-portal-copy.mjs            copy
 *   node tools/sync-portal-copy.mjs --check    fail if they have drifted
 *
 * One file, two homes. The file under `tools/` is the thing itself — opened
 * from a laptop it needs no server, no login and no network, which is the
 * whole point of it. The copy under `frontend/public/tools/` is the same
 * page, served by the portal at a link that can be sent.
 *
 * It is a copy rather than a build step because Vercel builds with the root
 * directory set to `frontend`, and a file that has to exist at build time is
 * better committed than generated by a script nobody remembers to run. This
 * script is how it is kept honest: run it after changing a tool, and the check
 * fails loudly if the two ever drift.
 *
 * `wrap: true` puts the page inside a document. Plot to Plan is authored as a
 * fragment — a title, its styles and its markup — because that is the shape
 * the Artifact publisher takes, and it is published there too. Served as a
 * plain file it needs the doctype, or the browser drops into quirks mode and
 * the percentage heights in the 3D stage collapse.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/* fileURLToPath, not the URL's pathname: a repo checked out under a folder with
   a space in its name arrives here as %20 otherwise, and the read fails */
const here = path.dirname(fileURLToPath(import.meta.url));
const pub = path.join(here, '..', 'frontend', 'public', 'tools');

const PAIRS = [
  { from: 'concept-deck-configurator.html', to: 'concept-deck.html', wrap: false },
  { from: 'area-planner.html', to: 'area-planner.html', wrap: true },
];

/** head is everything up to the end of the stylesheet; the rest is the body */
function wrapDocument(html) {
  const end = html.indexOf('</style>');
  const cut = end < 0 ? 0 : end + '</style>'.length;
  const head = html.slice(0, cut);
  const body = html.slice(cut);
  return '<!doctype html>\n<html lang="en">\n<head>\n' +
    '<meta charset="utf-8">\n' +
    '<meta name="viewport" content="width=device-width, initial-scale=1">\n' +
    head + '\n</head>\n<body>' + body + '\n</body>\n</html>\n';
}

const check = process.argv.includes('--check');
let drifted = 0;

for (const pair of PAIRS) {
  const source = path.join(here, pair.from);
  if (!fs.existsSync(source)) {
    console.error('missing source:', pair.from);
    process.exitCode = 1;
    continue;
  }
  const target = path.join(pub, pair.to);
  const raw = fs.readFileSync(source, 'utf8');
  const out = Buffer.from(pair.wrap ? wrapDocument(raw) : raw, 'utf8');
  const same = fs.existsSync(target) && Buffer.compare(out, fs.readFileSync(target)) === 0;

  if (check) {
    if (same) console.log('in step · public/tools/' + pair.to);
    else { console.error('OUT OF STEP — public/tools/' + pair.to + ' is not ' + pair.from); drifted++; }
    continue;
  }
  if (same) {
    console.log('already in step · ' + pair.to);
  } else {
    fs.mkdirSync(pub, { recursive: true });
    fs.writeFileSync(target, out);
    console.log('copied', (out.length / 1024).toFixed(0) + ' KB → public/tools/' + pair.to);
  }
}

if (check && drifted) {
  console.error('Run: node tools/sync-portal-copy.mjs');
  process.exit(1);
}
